def generate_c_array():
    """生成C语言数组格式"""
    # 按照chinese_font.h中的顺序
    chars = ['智', '能', '小', '车', '停', '止', '前', '进', '后', '退',
             '左', '转', '右', '速', '度', '接', '收', '状', '态']

    print("const uint8_t Chinese_Font_16x16[CH_COUNT][32] = {")

    for i, char in enumerate(chars):
        data = FONT_DATA[char]
        print(f"    /* {char} - index {i} */")
        print("    {", end="")
        for j, byte in enumerate(data):
            if j % 8 == 0:
                print("\n        ", end="")
            print(f"0x{byte:02X},", end="")
        print("\n    },")

    print("};")

if __name__ == '__main__':
    generate_c_array()
