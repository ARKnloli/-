/**
  * @brief  显示单个16x16中文字符
  * @param  x: 起始列 (0-127)
  * @param  y: 起始页 (0-7)
  * @param  index: 字符索引
  * @retval None
  */
void OLED_ShowChinese(uint8_t x, uint8_t y, Chinese_Char_Index index)
{
    if (index >= CH_COUNT) return;

    /* 使用OLED_ShowIcon显示16x16点阵 */
    OLED_ShowIcon(x, y, Chinese_Font_16x16[index]);
}

/**
  * @brief  显示中文字符串
  * @param  x: 起始列 (0-127)
  * @param  y: 起始页 (0-7)
  * @param  str: 字符索引数组
  * @param  len: 字符数量
  * @retval None
  */
void OLED_ShowChineseString(uint8_t x, uint8_t y, const Chinese_Char_Index *str, uint8_t len)
{
    uint8_t i;

    for (i = 0; i < len; i++) {
        OLED_ShowChinese(x + i * 16, y, str[i]);
    }
}
